#!/usr/bin/env python3
"""Rebuild benchmarks/workloads/ from the original public sources.

The output files are committed, so running a benchmark never needs network
access or a download that could change upstream. This script documents
exactly how they were made, and lets anyone check that: re-running it must
reproduce byte-identical files (their SHA-256 hashes are in SOURCES.md).

    python benchmarks/prepare_workloads.py

- perf_prompts.jsonl: 200 instructions from databricks-dolly-15k
  (CC BY-SA 3.0), sampled with a fixed seed, for the speed runs. Only the
  prompt *length* matters for speed (outputs are fixed-length), so the
  sample just needs to be realistic and fixed.
- gsm8k_test.jsonl: the full GSM8K test set (1,319 grade-school math word
  problems, MIT license), for the quality eval.
"""

import hashlib
import json
import random
import urllib.request
from pathlib import Path

DOLLY_URL = "https://huggingface.co/datasets/databricks/databricks-dolly-15k/resolve/main/databricks-dolly-15k.jsonl"
GSM8K_URL = "https://raw.githubusercontent.com/openai/grade-school-math/master/grade_school_math/data/test.jsonl"

OUT_DIR = Path(__file__).resolve().parent / "workloads"
N_PERF_PROMPTS = 200
SEED = 0
# Keeps prompt + 256 output tokens well inside a 4,096-token context window
# (roughly 4 characters per token for English text).
MAX_PROMPT_CHARS = 6000


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as resp:
        return resp.read()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_perf_prompts(dolly_raw: bytes) -> list[dict]:
    rows = [json.loads(line) for line in dolly_raw.decode().splitlines() if line.strip()]
    candidates = []
    for i, row in enumerate(rows):
        prompt = row["instruction"].strip()
        if row.get("context", "").strip():
            prompt += "\n\n" + row["context"].strip()
        if prompt and len(prompt) <= MAX_PROMPT_CHARS:
            candidates.append({"id": f"dolly-{i}", "category": row["category"], "prompt": prompt})
    return random.Random(SEED).sample(candidates, N_PERF_PROMPTS)


def build_gsm8k(gsm8k_raw: bytes) -> list[dict]:
    rows = [json.loads(line) for line in gsm8k_raw.decode().splitlines() if line.strip()]
    return [{"id": f"gsm8k-test-{i}", "question": r["question"], "answer": r["answer"]} for i, r in enumerate(rows)]


def write_jsonl(path: Path, rows: list[dict]) -> bytes:
    data = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows).encode()
    path.write_bytes(data)
    return data


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    dolly_raw, gsm8k_raw = fetch(DOLLY_URL), fetch(GSM8K_URL)

    perf = build_perf_prompts(dolly_raw)
    perf_bytes = write_jsonl(OUT_DIR / "perf_prompts.jsonl", perf)
    gsm8k = build_gsm8k(gsm8k_raw)
    gsm8k_bytes = write_jsonl(OUT_DIR / "gsm8k_test.jsonl", gsm8k)

    lengths = sorted(len(p["prompt"]) for p in perf)
    (OUT_DIR / "SOURCES.md").write_text(
        f"""# Workload provenance

Generated by `benchmarks/prepare_workloads.py`. Re-running it must reproduce
these files exactly; compare the hashes below.

| File | Rows | SHA-256 |
|---|---|---|
| perf_prompts.jsonl | {len(perf)} | `{sha256(perf_bytes)}` |
| gsm8k_test.jsonl | {len(gsm8k)} | `{sha256(gsm8k_bytes)}` |

## perf_prompts.jsonl
- Source: [databricks-dolly-15k]({DOLLY_URL}), SHA-256 of the downloaded file
  `{sha256(dolly_raw)}`.
- License: **CC BY-SA 3.0** (Databricks, Inc.). This derived file is shared
  under the same license; the rest of the repository is MIT.
- Built by: instruction, plus `\\n\\n` + context when the row has one;
  rows longer than {MAX_PROMPT_CHARS} characters dropped; {N_PERF_PROMPTS} sampled
  with `random.Random({SEED})`.
- Prompt length in characters: min {lengths[0]}, median {lengths[len(lengths) // 2]}, max {lengths[-1]}.

## gsm8k_test.jsonl
- Source: [GSM8K test split]({GSM8K_URL}) (OpenAI, *Training Verifiers to
  Solve Math Word Problems*, Cobbe et al. 2021), SHA-256 of the downloaded file
  `{sha256(gsm8k_raw)}`.
- License: **MIT**.
- Unchanged except for an added `id` field. The reference answer is the
  number after `####` in `answer`.
"""
    )
    print(f"wrote {len(perf)} perf prompts and {len(gsm8k)} GSM8K problems to {OUT_DIR}")


if __name__ == "__main__":
    main()
